// 统一的内联 SVG 图标集（线性、1.75 描边、currentColor）。
// 项目约定：不用 emoji 当图标，所有图标集中在此，尺寸由 size 控制。
import type { SVGProps } from "react";

interface IconProps extends Omit<SVGProps<SVGSVGElement>, "width" | "height"> {
  size?: number;
}

function base({ size = 20, ...rest }: IconProps) {
  return {
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 1.75,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    "aria-hidden": true,
    focusable: false,
    ...rest,
  };
}

/** 品牌标记：直接使用打包的应用图标，保证 UI 与 exe 图标完全一致 */
